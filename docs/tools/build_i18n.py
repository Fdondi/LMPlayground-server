# Ensure every language found in app strings ends up in the bundle, even if we
# don't have website-original translations yet — they'll fall back to English
# everywhere except FAQ + chat (which come from the app).
for code in APP:
    if code in BUNDLE: continue
    full = dict(EN)
    fill_app_strings(full, code)
    BUNDLE[code] = full

