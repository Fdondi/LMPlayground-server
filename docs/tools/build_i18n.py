def fill_app_strings(d, lang):
    src = APP.get(lang, {})
    for i in range(1, 15):
        if f"faq_q{i}" in src: d[f"faq.q{i}"] = src[f"faq_q{i}"]
        if f"faq_a{i}" in src: d[f"faq.a{i}"] = src[f"faq_a{i}"]
    # Privacy policy — mirrors the app copy so the hosted page localizes too.
    if "privacy_policy" in src: d["privacy.title"] = src["privacy_policy"]
    if "privacy_policy_effective_date" in src: d["privacy.date"] = src["privacy_policy_effective_date"]
    if "privacy_policy_intro" in src: d["privacy.intro"] = src["privacy_policy_intro"]
    for i in range(1, 8):
        if f"privacy_policy_s{i}_title" in src: d[f"privacy.s{i}.title"] = src[f"privacy_policy_s{i}_title"]
        if f"privacy_policy_s{i}_body" in src: d[f"privacy.s{i}.body"] = src[f"privacy_policy_s{i}_body"]
    if "screenshot_chat_question" in src: d["phone.q"] = src["screenshot_chat_question"]
    if "screenshot_chat_response" in src: d["phone.a"] = src["screenshot_chat_response"]
    if "supports_your_language" in src: d["models.supports_your_language"] = src["supports_your_language"]
    if "other_models" in src: d["models.other_models"] = src["other_models"]
    # System-prompts + tools sections — reuse the app's own (often already
    # localized) copy. Several website keys share one app string.
    if "system_prompts" in src:
        d["prompts.eyebrow"] = src["system_prompts"]
        d["nav.prompts"] = src["system_prompts"]
        d["footer.product.prompts"] = src["system_prompts"]
    if "system_prompt_new" in src: d["prompts.new"] = src["system_prompt_new"]
    if "tools" in src:
        d["tools.eyebrow"] = src["tools"]
        d["nav.tools"] = src["tools"]
        d["footer.product.tools"] = src["tools"]
        d["models.tab.tools"] = src["tools"]
    if "tools_section_intro" in src: d["tools.note"] = src["tools_section_intro"]
    if "tool_run_javascript_title" in src: d["tools.t1.title"] = src["tool_run_javascript_title"]
    if "tool_run_javascript_desc" in src: d["tools.t1.body"] = src["tool_run_javascript_desc"]
    if "tool_web_search_title" in src: d["tools.t2.title"] = src["tool_web_search_title"]
    if "tool_web_search_desc" in src: d["tools.t2.body"] = src["tool_web_search_desc"]
    if "tool_web_fetch_title" in src: d["tools.t3.title"] = src["tool_web_fetch_title"]
    if "tool_web_fetch_desc" in src: d["tools.t3.body"] = src["tool_web_fetch_desc"]
    return d

